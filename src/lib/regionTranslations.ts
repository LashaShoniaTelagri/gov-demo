export const translateCrop = (crop: string, language: string): string => {
  // If crop translation exists
  if (cropTranslations[crop]) {
    if (language === 'en') {
      return cropTranslations[crop].en;
    } else if (language === 'ru') {
      return cropTranslations[crop].ru;
    }
  }
  // Otherwise return as is (Georgian stays Georgian if not found)
  return crop;
};

// Helper function to get translated farmer name
export const getFarmerName = (farmer: { name: string; surname: string; nameEn: string; surnameEn: string; nameRu?: string; surnameRu?: string }, language: string): string => {
  if (language === 'ka') {
    return `${farmer.name} ${farmer.surname}`;
  } else if (language === 'ru') {
    const firstName = farmer.nameRu || farmer.nameEn;
    const lastName = farmer.surnameRu || farmer.surnameEn;
    return `${firstName} ${lastName}`;
  } else {
    // English (default)
    return `${farmer.nameEn} ${farmer.surnameEn}`;
  }
};

// Helper function to get translated company name
export const getCompanyName = (farmer: { company: string; companyEn?: string; companyRu?: string }, language: string): string => {
  if (language === 'ka') {
    return farmer.company;
  } else if (language === 'ru') {
    return farmer.companyRu || farmer.companyEn || farmer.company;
  } else {
    // English (default)
    return farmer.companyEn || farmer.company;
  }
};
